//! A Vellum greeter rendszerallapota (`/var/lib/vellum-greeter`).
//!
//! A greeter greetd alatt, sajat rendszerfelhasznalokent fut egy minimalis
//! Hyprlandben. A `/home`-hoz nem fer hozza, ezert minden, amit a desktoprol
//! tudnia kell, ebbe a mappaba kerul: a paletta, a hatterkep masolata es a
//! monitor-elrendezes.
//!
//! A mappa root tulajdonu, a benne levo fajlokat a `greeter-install` a
//! felhasznalora chownolja. Igy a daemon root nelkul frissitheti oket, de uj
//! fajlt nem hozhat letre: ami nincs ott, az nincs telepitve.
//!
//! Az elrendezes szandekosan adat, nem Lua. A greeter compositor konfigja
//! (`greeter/hyprland.lua`) root tulajdonu, es soronkent ellenorizve olvassa
//! be. Egy felhasznalo altal irhato Lua modul a greeter felhasznalo neveben
//! futtatna tetszoleges kodot.

use crate::modules::hypr::MonitorSetting;
use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

const DEFAULT_DIR: &str = "/var/lib/vellum-greeter";
const LAYOUT_NAME: &str = "layout.conf";
const LAYOUT_HEADER: &str = "# Generated by the Vellum Shell backend – ne szerkeszd kezzel.\n\
# A greeter compositor (greeter/hyprland.lua) soronkent, ellenorizve olvassa.\n";

/// A greeter allapotmappaja, ha van mit irni.
///
/// A `VELLUM_GREETER_DIR` a tesztek es az elonezet homokozoja. Nelkule a
/// rendszermappa jon, de teszt alatt (`VELLUM_NO_SIDE_EFFECTS`) ahhoz nem
/// nyulunk: kulonben minden futas atirna az ELO greeter palettajat.
pub fn state_dir() -> Option<PathBuf> {
    match std::env::var_os("VELLUM_GREETER_DIR") {
        Some(dir) if !dir.is_empty() => Some(PathBuf::from(dir)),
        _ => crate::theme::side_effects_enabled().then(|| PathBuf::from(DEFAULT_DIR)),
    }
}

/// Helyben ir, hogy eleg legyen a fajlra kapott irasi jog (a mappa root
/// tulajdonu). `None`, ha a greeter nincs telepitve vagy nincs jogunk: az nem
/// hiba, csak nincs kit frissiteni.
pub fn write_if_writable(path: &Path, payload: &[u8]) -> Option<bool> {
    if let Ok(existing) = std::fs::read(path) {
        if existing == payload {
            return Some(false);
        }
        return std::fs::write(path, payload).ok().map(|()| true);
    }

    if !path.parent().is_some_and(Path::is_dir) {
        return None;
    }
    std::fs::write(path, payload).ok().map(|()| true)
}

/// A billentyuzetkiosztas a felhasznalo munkamenetebol: a jelszot ugyanazzal
/// a kiosztassal kell begepelni, amivel beallitotta.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Keyboard {
    pub layout: String,
    pub variant: String,
    pub options: String,
}

/// Kiirja az elrendezest. A `monitors` a teljes elo allapot.
pub fn write_layout(monitors: &[MonitorSetting], keyboard: &Keyboard) -> Option<bool> {
    let path = state_dir()?.join(LAYOUT_NAME);
    let previous = std::fs::read_to_string(&path).unwrap_or_default();
    write_if_writable(&path, render_layout(monitors, keyboard, &previous).as_bytes())
}

/// Az elrendezes szoveges alakja.
///
/// A most nem csatlakoztatott kijelzok korabbi sorai megmaradnak: egy
/// kikapcsolt TV vagy egy dokkolo nelkuli indulas ne felejtse el, hova
/// tartozik a kijelzo a kovetkezo bejelentkezeskor.
pub fn render_layout(monitors: &[MonitorSetting], keyboard: &Keyboard, previous: &str) -> String {
    let mut out = String::from(LAYOUT_HEADER);
    for (key, value) in [
        ("kb_layout", &keyboard.layout),
        ("kb_variant", &keyboard.variant),
        ("kb_options", &keyboard.options),
    ] {
        if is_keyboard_value(value) {
            out.push_str(&format!("{key}={value}\n"));
        }
    }

    let mut written = BTreeSet::new();
    for setting in monitors {
        if let Some(line) = monitor_line(setting) {
            written.insert(setting.output.clone());
            out.push_str(&line);
        }
    }

    for line in previous.lines() {
        let Some(name) = line_output(line) else { continue };
        if written.insert(name.to_string()) {
            out.push_str(line);
            out.push('\n');
        }
    }

    out
}

fn monitor_line(setting: &MonitorSetting) -> Option<String> {
    let name = setting.output.as_str();
    if !is_output_name(name) {
        return None;
    }
    if setting.disabled {
        return Some(format!("disabled={name}\n"));
    }

    let mode = setting.mode.as_deref().filter(|mode| is_mode(mode))?;
    let position = setting.position.as_deref().filter(|position| is_position(position))?;
    let scale = setting.scale.filter(|scale| scale.is_finite() && *scale > 0.0).unwrap_or(1.0);
    let transform = setting.transform.filter(|transform| *transform <= 7).unwrap_or(0);
    Some(format!("monitor={name} {mode} {position} {scale} {transform}\n"))
}

/// Egy korabbi sor kijelzoneve, ha a sor kijelzot ir le.
fn line_output(line: &str) -> Option<&str> {
    let name = if let Some(rest) = line.strip_prefix("monitor=") {
        rest.split(' ').next()?
    } else {
        line.strip_prefix("disabled=")?
    };
    is_output_name(name).then_some(name)
}

// Ugyanazok a mintak, mint a `greeter/hyprland.lua`-ban: ami itt atmegy, azt
// a greeter is elfogadja.

fn is_output_name(value: &str) -> bool {
    !value.is_empty()
        && value.chars().all(|ch| ch.is_ascii_alphanumeric() || matches!(ch, '-' | '_' | '.'))
}

fn is_mode(value: &str) -> bool {
    let Some((size, rate)) = value.split_once('@') else {
        return false;
    };
    let rate_ok = match rate.split_once('.') {
        Some((whole, fraction)) => is_digits(whole) && is_digits(fraction),
        None => is_digits(rate),
    };
    is_pair(size, false) && rate_ok
}

fn is_position(value: &str) -> bool {
    is_pair(value, true)
}

fn is_pair(value: &str, signed: bool) -> bool {
    let Some((first, second)) = value.split_once('x') else {
        return false;
    };
    let number = |part: &str| {
        let digits = if signed { part.strip_prefix('-').unwrap_or(part) } else { part };
        is_digits(digits)
    };
    number(first) && number(second)
}

fn is_digits(value: &str) -> bool {
    !value.is_empty() && value.chars().all(|ch| ch.is_ascii_digit())
}

fn is_keyboard_value(value: &str) -> bool {
    value.chars().all(|ch| {
        ch.is_ascii_alphanumeric() || matches!(ch, '_' | ',' | ':' | '(' | ')' | '+' | '-')
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn monitor(output: &str, mode: &str, position: &str) -> MonitorSetting {
        MonitorSetting {
            output: output.into(),
            mode: Some(mode.into()),
            position: Some(position.into()),
            scale: Some(1.0),
            transform: Some(0),
            ..Default::default()
        }
    }

    fn keyboard() -> Keyboard {
        Keyboard {
            layout: "hu,us".into(),
            variant: String::new(),
            options: "grp:alt_shift_toggle".into(),
        }
    }

    #[test]
    fn the_layout_is_one_validated_line_per_output() {
        let mut off = monitor("DP-3", "", "");
        off.disabled = true;
        let monitors = [
            monitor("DP-2", "1920x1080@60", "0x0"),
            monitor("HDMI-A-1", "2560x1440@144", "1920x0"),
            off,
        ];
        let output = render_layout(&monitors, &keyboard(), "");
        assert_eq!(
            output,
            format!(
                "{LAYOUT_HEADER}kb_layout=hu,us\nkb_variant=\nkb_options=grp:alt_shift_toggle\n\
                 monitor=DP-2 1920x1080@60 0x0 1 0\n\
                 monitor=HDMI-A-1 2560x1440@144 1920x0 1 0\n\
                 disabled=DP-3\n"
            )
        );
    }

    #[test]
    fn fractional_scale_and_negative_position_survive() {
        let mut setting = monitor("eDP-1", "2880x1800@120.00", "-1440x0");
        setting.scale = Some(1.5);
        setting.transform = Some(1);
        let output = render_layout(&[setting], &Keyboard::default(), "");
        assert!(output.contains("\nmonitor=eDP-1 2880x1800@120.00 -1440x0 1.5 1\n"), "{output}");
    }

    /// A konfigot root tulajdonu Lua olvassa, de a fajl a felhasznaloe: ami
    /// nem illik a mintara, az bele se kerul.
    #[test]
    fn unsafe_values_are_dropped() {
        let monitors = [
            monitor("DP-1\"); os.execute(\"x", "1920x1080@60", "0x0"),
            monitor("DP-2", "1920x1080; x", "0x0"),
        ];
        let keyboard = Keyboard { layout: "us\nmonitor=evil".into(), ..Default::default() };
        let output = render_layout(&monitors, &keyboard, "");
        assert_eq!(output, format!("{LAYOUT_HEADER}kb_variant=\nkb_options=\n"));
    }

    #[test]
    fn a_disconnected_output_keeps_its_previous_line() {
        let previous = format!(
            "{LAYOUT_HEADER}kb_layout=us\n\
             monitor=DP-2 1920x1080@60 0x0 1 0\n\
             monitor=HDMI-A-1 1920x1080@144 1920x0 1 0\n"
        );
        let output =
            render_layout(&[monitor("DP-2", "1920x1080@60", "1920x0")], &keyboard(), &previous);
        assert!(output.contains("\nmonitor=DP-2 1920x1080@60 1920x0 1 0\n"), "{output}");
        assert!(output.contains("\nmonitor=HDMI-A-1 1920x1080@144 1920x0 1 0\n"), "{output}");
        assert_eq!(output.matches("DP-2").count(), 1, "{output}");
        assert!(!output.contains("kb_layout=us\n"), "{output}");
    }

    #[test]
    fn an_unwritable_or_missing_target_is_not_an_error() {
        let dir =
            std::env::temp_dir().join(format!("vellum-greeter-write-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        assert_eq!(write_if_writable(&dir.join("theme.json"), b"x"), None);

        std::fs::create_dir_all(&dir).unwrap();
        let target = dir.join("theme.json");
        assert_eq!(write_if_writable(&target, b"x"), Some(true));
        assert_eq!(write_if_writable(&target, b"x"), Some(false));
        assert_eq!(write_if_writable(&target, b"y"), Some(true));
        std::fs::remove_dir_all(&dir).ok();
    }
}
